package com.irurueta.authserver.bff.user;

import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.oidcLogin;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest
@AutoConfigureMockMvc
class UserControllerTest {

    @Autowired
    private MockMvc mockMvc;

    @Test
    void userAnonymousReturnsUnauthorized() throws Exception {
        mockMvc.perform(get("/bff/user")).andExpect(status().isUnauthorized());
    }

    @Test
    void userAuthenticatedReturnsSubject() throws Exception {
        mockMvc.perform(get("/bff/user")
                        .with(oidcLogin().idToken(token -> token.subject("demo-user"))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.subject").value("demo-user"));
    }
}
