package com.irurueta.authserver.authorization.domain.ott;

/**
 * Channel through which a one-time token reaches the user.
 */
public enum OttChannel {
    /** The token is sent to the verified e-mail address of the account. */
    EMAIL,
    /** The token is sent as a text message to the verified phone number of the account. */
    SMS
}
