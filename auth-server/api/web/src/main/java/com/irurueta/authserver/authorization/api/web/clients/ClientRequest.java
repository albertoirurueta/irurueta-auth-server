package com.irurueta.authserver.authorization.api.web.clients;

import com.irurueta.authserver.authorization.domain.clients.ClientRegistration;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import java.time.Duration;
import java.util.List;

/**
 * Body of the create and update client requests. It never carries a secret: secrets are generated by the server.
 *
 * @param clientId          public identifier of the client.
 * @param name              human readable name.
 * @param confidential      whether the client can keep a secret.
 * @param authMethods       client authentication methods.
 * @param grantTypes        allowed grant types.
 * @param redirectUris      allowed redirect URIs.
 * @param scopes            allowed scopes.
 * @param requireProofKey   whether PKCE is required.
 * @param audiences         audiences of the issued access tokens; empty means the client identifier.
 * @param accessTokenTtl    lifetime of access tokens.
 * @param refreshTokenTtl   lifetime of refresh tokens.
 * @param accessTokenFormat {@code self-contained} or {@code reference}; defaults to {@code self-contained}.
 * @param reuseRefreshTokens whether refresh tokens are reused instead of rotated.
 */
@Schema(description = "Definition of a registered client; it never contains a secret")
public record ClientRequest(
        @NotBlank String clientId, @NotBlank String name, boolean confidential,
        @NotNull List<String> authMethods, @NotNull List<String> grantTypes, @NotNull List<String> redirectUris,
        @NotNull List<String> scopes, boolean requireProofKey, List<String> audiences,
        @NotNull Duration accessTokenTtl, @NotNull Duration refreshTokenTtl, String accessTokenFormat,
        boolean reuseRefreshTokens) {

    /**
     * Creates a request, copying its collections.
     */
    public ClientRequest {
        authMethods = authMethods == null ? null : List.copyOf(authMethods);
        grantTypes = grantTypes == null ? null : List.copyOf(grantTypes);
        redirectUris = redirectUris == null ? null : List.copyOf(redirectUris);
        scopes = scopes == null ? null : List.copyOf(scopes);
        audiences = audiences == null ? List.of() : List.copyOf(audiences);
    }

    /**
     * Maps the request to a client registration.
     *
     * @return the registration.
     * @throws IllegalArgumentException if the registration is not valid.
     */
    public ClientRegistration toRegistration() {
        return new ClientRegistration(clientId, name, confidential, authMethods, grantTypes, redirectUris, scopes,
                requireProofKey, audiences, accessTokenTtl, refreshTokenTtl,
                accessTokenFormat == null || accessTokenFormat.isBlank()
                        ? ClientRegistration.FORMAT_SELF_CONTAINED : accessTokenFormat,
                reuseRefreshTokens);
    }
}
